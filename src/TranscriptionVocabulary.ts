import { deepEqual, isResolved } from "alchemy/Diff";
import * as Provider from "alchemy/Provider";
import { Resource } from "alchemy/Resource";
import * as Effect from "effect/Effect";
import { listAll, Mux } from "./Api.ts";
import type { components } from "./generated/mux-api.ts";
import type { Providers } from "./Providers.ts";

type Schemas = components["schemas"];

export type TranscriptionVocabularyProps = Schemas["CreateTranscriptionVocabularyRequest"];
export type TranscriptionVocabularyAttributes = Schemas["TranscriptionVocabulary"];

export type TranscriptionVocabulary = Resource<
  "Mux.TranscriptionVocabulary",
  TranscriptionVocabularyProps,
  TranscriptionVocabularyAttributes,
  never,
  Providers
>;

/**
 * Words and phrases (product names, speaker names, jargon) that improve live
 * auto-generated captions. Reference its `id` from a live stream's
 * `generated_subtitles[].transcription_vocabulary_ids`. Updates in place.
 * @see https://www.mux.com/docs/guides/add-autogenerated-captions-and-use-transcripts
 *
 * **Example:**
 * ```typescript
 * const vocab = yield* Mux.TranscriptionVocabulary("product-terms", {
 *   name: "Product terms",
 *   phrases: ["Mux", "Alchemy", "HLS"],
 * });
 * ```
 *
 * @resource
 */
export const TranscriptionVocabulary = Resource<TranscriptionVocabulary>(
  "Mux.TranscriptionVocabulary",
);

export const TranscriptionVocabularyProvider = () =>
  Provider.effect(
    TranscriptionVocabulary,
    Effect.gen(function* () {
      const mux = yield* Mux;
      const path = (id: string) => `/video/v1/transcription-vocabularies/${id}`;

      return {
        stables: ["id", "created_at"],
        list: () =>
          listAll<TranscriptionVocabularyAttributes>(mux, "/video/v1/transcription-vocabularies"),
        diff: Effect.fn(function* ({ olds, news, output }) {
          if (!isResolved(news) || output === undefined) return undefined;
          return deepEqual(olds, news) ? undefined : ({ action: "update" } as const);
        }),
        reconcile: Effect.fn(function* ({ news, output }) {
          if (output === undefined) {
            return yield* mux.request<TranscriptionVocabularyAttributes>(
              "POST",
              "/video/v1/transcription-vocabularies",
              news,
            );
          }
          return yield* mux.request<TranscriptionVocabularyAttributes>("PUT", path(output.id), news);
        }),
        delete: Effect.fn(function* ({ output }) {
          yield* mux
            .request("DELETE", path(output.id))
            .pipe(Effect.catchTag("NotFound", () => Effect.void));
        }),
        read: Effect.fn(function* ({ output }) {
          if (!output?.id) return undefined;
          return yield* mux
            .request<TranscriptionVocabularyAttributes>("GET", path(output.id))
            .pipe(Effect.catchTag("NotFound", () => Effect.undefined));
        }),
      };
    }),
  );
